    def fit(self, X_np, use_prior=1):
        X_tensor = torch.tensor(X_np, dtype=torch.float32)
        N, D = X_tensor.shape

        # === 自動設定閾值 ===
        # 0.8 是一個經驗法則，代表我們期望 Cluster 的緊密度是整體的 80%
        if self.split_threshold is None:
            # $$H \approx \frac{D}{2} (1 + \ln(2\pi) + \ln(\sigma^2))$$
            self.split_threshold = 0.5 * D * (1 + np.log(2 * np.pi) + np.log(1.0))
            if self.verbose:
                print(f"Auto-configured Split Threshold: {self.split_threshold:.2f} (based on D={D}, tightness=0.8)")


        # 1. Step A 帶入 mode
        rho = self._step_a_calculate_prior(X_np, mode=use_prior)

        # 2. 初始化 K=1 (Fix 1: 使用全局均值初始化 Mu)
        global_mean = torch.mean(X_tensor, dim=0, keepdim=True) # [1, D]
        # self.model = DiagnosableGMM(D, 1, rho, init_means=global_mean)
        # MLWA
        self.model = DiagnosableGMM(D, 1, rho, init_means=global_mean, beta_mult=self.beta_mult)
        optimizer = optim.Adam(self.model.parameters(), lr=self.lr)

        if self.verbose: print(f"Starting Training (Initial K=1)...")

        for epoch in range(1, self.max_epochs + 1):
            self.model.train()
            optimizer.zero_grad()
            loss, q_phi, _ = self.model(X_tensor)
            loss.backward()
            optimizer.step()

            self.model.temperature = max(0.1, self.model.temperature * 0.98)

            self.history['loss'].append(loss.item())
            self.history['k'].append(self.model.K)
            self.history['phi'].append(q_phi.detach().numpy())

            if epoch % self.split_interval == 0:
                scores = self.model.get_cluster_diagnostics(X_tensor)
                worst_idx = np.argmax(scores)
                worst_score = scores[worst_idx]

                if self.verbose:
                    # 顯示當前狀態
                    phi_curr = q_phi.detach().numpy()
                    print(f"Epoch {epoch}: K={self.model.K}, Max NLL={worst_score:.2f}")
                    # print(f"   Phi[0]={phi_curr[0]:.2f}, Phi[9]={phi_curr[9]:.2f}")

                # MLWA
                can_split = (self.max_components is None) or (self.model.K < self.max_components)

                if (worst_score > self.split_threshold) and can_split:
                    if self.verbose: print(f"   >>> Splitting Cluster {worst_idx}...")
                    self.model = self._expand_model(self.model, worst_idx)
                    optimizer = optim.Adam(self.model.parameters(), lr=self.lr)
                elif (worst_score > self.split_threshold) and (not can_split):
                    if self.verbose:
                        print(f"   >>> Split blocked: K reached max_components={self.max_components}")
                # if worst_score > self.split_threshold:
                #     if self.verbose: print(f"   >>> Splitting Cluster {worst_idx}...")
                #     self.model = self._expand_model(self.model, worst_idx)
                #     optimizer = optim.Adam(self.model.parameters(), lr=self.lr)

        if self.verbose: print("Training Completed.")
        return self