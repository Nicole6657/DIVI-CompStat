class DIVIClustering:


    def __init__(self,
                split_threshold=22.0,
                split_interval=60,
                max_epochs=300,
                lr=0.05,
                max_components=None,
                # MLWA
                beta_mult=1.0,
                rough_k=3,
                verbose=True):
        self.split_threshold = split_threshold
        self.split_interval = split_interval
        self.max_epochs = max_epochs
        self.lr = lr
        self.max_components = max_components
        # MLWA
        self.beta_mult = beta_mult
        self.rough_k = rough_k
        self.verbose = verbose

        self.model = None
        self.history = {'loss': [], 'k': [], 'phi': []}


    def _step_a_calculate_prior(self, X, mode=1, w_kw=1.0, w_llr=1.0):
        """
        執行數據啟發式先驗計算。
        mode=1: Informative (KW Test + LLR)
        mode=2: Non-informative (0.5)
        mode=3: Random Prior
        """
        N, D = X.shape

        if mode == 1:
            if self.verbose: print("   -> Mode 1: Computing Combined KW & LLR scores...")

            # 預分群：使用自適應 K
            # k_rough = min(3, N)
            k_rough = min(self.rough_k, N)
            kmeans = KMeans(n_clusters=k_rough, random_state=42).fit(X)
            labels = kmeans.labels_

            final_scores = []
            for j in range(D):
                feat = X[:, j]
                groups = [feat[labels == k] for k in range(k_rough) if len(feat[labels == k]) > 0]

                # --- (A) Kruskal-Wallis 統計量 ---
                kw_stat = 0
                if len(groups) > 1:
                    try:
                        stat, _ = stats.kruskal(*groups)
                        kw_stat = np.log1p(stat)
                    except: kw_stat = 0

                # --- (B) LLR (Log-Likelihood Ratio) 近似 ---
                # H0: 全域高斯 (Global Gaussian)
                var_0 = np.var(feat) + 1e-6
                ll_0 = -0.5 * np.sum((feat - np.mean(feat))**2) / var_0 - N * 0.5 * np.log(var_0)

                # H1: 分群高斯 (Clustered Gaussian)
                ll_1 = 0
                for group in groups:
                    if len(group) > 1:
                        v_k = np.var(group) + 1e-6
                        ll_1 += -0.5 * np.sum((group - np.mean(group))**2) / v_k - len(group) * 0.5 * np.log(v_k)

                llr_stat = max(0, ll_1 - ll_0)
                llr_stat = np.log1p(llr_stat) # 壓縮極端值

                # 結合分數
                final_scores.append(w_kw * kw_stat + w_llr * llr_stat)

            # 歸一化與轉換
            final_scores = np.array(final_scores)
            norm = (final_scores - final_scores.min()) / (final_scores.max() - final_scores.min() + 1e-9)

            # 使用 scale=6 增強區分度，並加上 clamp 確保數值穩定
            logits = (norm - 0.5) * 6
            rho = torch.sigmoid(torch.tensor(logits, dtype=torch.float32))
            rho = torch.clamp(rho, 0.01, 0.99) # 關鍵：防止梯度消失或 NaN

        elif mode == 2:
            rho = torch.full((D,), 0.5, dtype=torch.float32)
        elif mode == 3:
            rho = torch.rand(D, dtype=torch.float32)

        return rho


    def _expand_model(self, old_model, split_idx):
        D, K = old_model.D, old_model.K

        # 建立新模型 (繼承 Prior)
        # new_model = DiagnosableGMM(D, K + 1, old_model.prior_phi_probs, temperature=old_model.temperature)
        # MLWA
        new_model = DiagnosableGMM(
            D, K + 1,
            old_model.prior_phi_probs,
            temperature=old_model.temperature,
            beta_mult=old_model.beta_mult
        )

        # 1. 繼承 Phi (關鍵！不要重置)
        with torch.no_grad():
            new_model.phi_logits.copy_(old_model.phi_logits)

            # 2. 繼承 Mu
            old_mu = old_model.q_mu.data
            target_mu = old_mu[split_idx]
            mu_a = target_mu + torch.randn(D) * 0.2 # 縮小擾動
            mu_b = target_mu - torch.randn(D) * 0.2

            keep_idx = [i for i in range(K) if i != split_idx]
            if keep_idx:
                new_mus = torch.cat([old_mu[keep_idx], mu_a.unsqueeze(0), mu_b.unsqueeze(0)], dim=0)
            else:
                new_mus = torch.cat([mu_a.unsqueeze(0), mu_b.unsqueeze(0)], dim=0)
            new_model.q_mu.copy_(new_mus)

            # 3. 繼承 LogVar (保持寬度)
            old_logvar = old_model.q_logvar.data
            target_logvar = old_logvar[split_idx]
            if keep_idx:
                new_logvars = torch.cat([old_logvar[keep_idx], target_logvar.unsqueeze(0), target_logvar.unsqueeze(0)], dim=0)
            else:
                new_logvars = torch.cat([target_logvar.unsqueeze(0), target_logvar.unsqueeze(0)], dim=0)
            new_model.q_logvar.copy_(new_logvars)

        return new_model
